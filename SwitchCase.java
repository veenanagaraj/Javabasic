package module1programs;

public class SwitchCase {

	public static void main(String[] args) {
		{
			switch(1)
			{
			case 1: System.out.println("Chrome Browser");
			        break;
			        
			case 2: System.out.println("Firefox browser");
				    break;
				
			case 3: System.out.println("Edge");
					break;
					
			case 4: System.out.println("Safari");
			        break;
			
		   default: System.out.println("Sorry but your selection is wrong");
			}
		}

	}

}
