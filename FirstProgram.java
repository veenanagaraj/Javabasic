package module1programs;

public class FirstProgram {
	static void add()
	{
int a=15;
int b=3;
int c=a+b;
System.out.println(c);
}
	
	static void sub()
	{	
int a1=40;
int b1=8;
int c1=a1-b1;
System.out.println(c1);
}

	static void mul()
	{	
int a2=40;
int b2=8;
int c2=a2*b2;
System.out.println(c2);
}
	
	static void div()
	{	
int a3=40;
int b3=8;
int c3=a3/b3;
System.out.println(c3);
}
	
	static void mod()
	{	
int a4=40;
int b4=8;
int c4=a4/b4;
System.out.println(c4);
}
	
	public static void main(String[] args) 
	{	
		add();
		sub();
		mul();
		div();
		mod();
	
	}
}
